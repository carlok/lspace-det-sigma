def create_D_n(n):
    PD=[]
    PD_tangle=[(12,3,13,1),(3,12,4,11),(15,6,16,5),(10,7,11,6),(7,10,8,9),
               (13,9,14,2),(4,17,5,16),(8,15,18,14)]
    for k in range(2*n+1):
        PD=PD+[tuple(x+16*k for x in c) for c in PD_tangle]
    PD=PD[:-2]
    PD.append((4+16*k,1,5+16*k,16+16*k))
    PD.append((8+16*k,15+16*k,2,14+16*k))
    return PD
